#!/bin/sh
# Regenerates message_id.inc and fetch.terse using the workspace's `terse` tool.
# Set CARGO if cargo is not on PATH (e.g. CARGO=~/.cargo/bin/cargo).
set -eu
cd "$(dirname "$0")"
terse() { "${CARGO:-cargo}" run -q -p terse-cli --bin terse -- "$@"; }
id=$(terse hash message.txt)
{
    echo "; Generated by build.sh: the blob ID (BLAKE3-256) of message.txt."
    echo "message_id:"
    echo "        db $(echo "$id" | sed 's/../0x&,/g; s/,$//')"
} > message_id.inc
bin=fetch.bin
trap 'rm -f "$bin"' EXIT
terse asm fetch.asm -o "$bin"
terse pack --rom "$bin" --title fetch --ram-pages 4 --device 2:0 --device 4:0 -o fetch.terse
