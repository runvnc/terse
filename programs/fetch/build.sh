#!/bin/sh
# Regenerates message_id.h (the blob ID of message.txt, from `terse hash`)
# and builds fetch.terse from fetch.c and programs/lib with clang (riscv32
# target), ld.lld, llvm-objcopy and the workspace's `terse pack`.
#   ./build.sh [<out dir>]     default: this directory (message_id.h is
#                              always written here)
# Set TERSE to a built `terse` binary to skip cargo, or CARGO if cargo is
# not on PATH; CLANG, LLD and OBJCOPY name the tools (defaults: clang,
# ld.lld, llvm-objcopy). The flags and the order of the objects are those
# of crates/terse-cli/tests/common/mod.rs, which checks that message_id.h
# and fetch.terse are up to date.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
lib="$here/../lib"
out=$(cd "${1:-$here}" && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
if [ -n "${TERSE:-}" ]; then
    terse() { "$TERSE" "$@"; }
else
    terse() { "${CARGO:-cargo}" run -q --manifest-path "$here/../../Cargo.toml" -p terse-cli --bin terse -- "$@"; }
fi

id=$(terse hash "$here/message.txt")
{
    echo "/* Generated by build.sh: the blob ID (BLAKE3-256) of message.txt. */"
    echo "static const uint8_t message_id[32] = {"
    echo "    $(echo "$id" | sed 's/../0x&, /g; s/, $//'),"
    echo "};"
} > "$here/message_id.h"

cd "$tmp"
cflags="--target=riscv32-unknown-elf -march=rv32imc -mabi=ilp32 -Os -ffreestanding -nostdlib -fno-builtin -ffunction-sections -fdata-sections"
n=0
for src in "$lib/crt0.S" "$here/fetch.c" "$lib/terse.c"; do
    "${CLANG:-clang}" $cflags -I "$lib" -c "$src" -o "$n.o"
    n=$((n + 1))
done
"${LLD:-ld.lld}" -T "$lib/terse.ld" --gc-sections 0.o 1.o 2.o -o fetch.elf
"${OBJCOPY:-llvm-objcopy}" -O binary fetch.elf fetch.bin
terse pack --rom fetch.bin --title fetch --ram-pages 1 --device 2:0 --device 4:0 -o "$out/fetch.terse"
