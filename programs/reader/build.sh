#!/bin/sh
# Regenerates manual_id.h (the blob ID of the manual's index, the first
# line of docs/manual/build/manifest, which `terse manual build` writes)
# and builds reader.terse from reader.c and programs/lib with
# clang (riscv32), ld.lld, llvm-objcopy and the workspace's `terse pack`.
#   ./build.sh [<out dir>]     default: this directory
# Set TERSE to a built `terse` binary to skip cargo, or CARGO if cargo is
# not on PATH; CLANG, LLD and OBJCOPY name the tools (defaults: clang,
# ld.lld, llvm-objcopy). The flags and the order of the objects are those
# of crates/terse-cli/tests/common/mod.rs, which checks that reader.terse is
# up to date (and crates/terse-cli/tests/reader.rs that it holds the
# manual's current index ID). programs/shell/build.sh writes the shell's
# own copy (programs/shell/manual_id.h) the same way: run both after
# `terse manual build`.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
lib="$here/../lib"
out=$(cd "${1:-$here}" && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
if [ -n "${TERSE:-}" ]; then
    terse() { "$TERSE" "$@"; }
else
    terse() { "${CARGO:-cargo}" run -q --manifest-path "$here/../../Cargo.toml" -p terse-cli --bin terse -- "$@"; }
fi

id=$(head -n 1 "$here/../../docs/manual/build/manifest" | cut -d ' ' -f 1)
{
    echo "/* Generated by build.sh: the blob ID (BLAKE3-256) of the manual's index,"
    echo " * from docs/manual/build/manifest. */"
    echo "static const uint8_t manual_index[32] = {"
    echo "    $(echo "$id" | sed 's/../0x&, /g; s/, $//'),"
    echo "};"
} > "$here/manual_id.h"

cd "$tmp"
cflags="--target=riscv32-unknown-elf -march=rv32imc -mabi=ilp32 -Os -ffreestanding -nostdlib -fno-builtin -ffunction-sections -fdata-sections"
n=0
for src in "$lib/crt0.S" "$here/reader.c" "$lib/terse.c"; do
    "${CLANG:-clang}" $cflags -I "$lib" -c "$src" -o "$n.o"
    n=$((n + 1))
done
"${LLD:-ld.lld}" -T "$lib/terse.ld" --gc-sections 0.o 1.o 2.o -o reader.elf
"${OBJCOPY:-llvm-objcopy}" -O binary reader.elf reader.bin
terse pack --rom reader.bin --title reader --ram-pages 42 --device 2:0 --device 4:0 --device 7:0 --device 10:0 -o "$out/reader.terse"
