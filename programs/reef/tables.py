"""Writes tables.h for reef.c: the stroke font and a sine table.

    python3 tables.py <arcade.rs> > tables.h

<arcade.rs> is the arcade font's glyph table, crates/terse-mame-crt/src/arcade.rs
(this project's own Apache-2.0 glyphs): reef keeps the capitals, the digits
and a few signs, as polylines on its grid with every coordinate doubled
(the grid has half units), one byte a point.
"""
import math
import re
import sys

src = open(sys.argv[1]).read()
want = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-.,:/!?%+'<>"
g = {}
for m in re.finditer(r"\('(\\'|.)', \"([^\"]*)\"\)", src):
    c = m.group(1)
    if c == "\\'":
        c = "'"
    if c in want and c not in g:
        g[c] = m.group(2)
# The grid here stops at y = 11: the comma's tail is a little shorter.
g[','] = "2.5,9 2.5,10 1.5,11"
out = []
idx = []
for c in want:
    idx.append(len(out))
    for k, poly in enumerate(g[c].split('/')):
        for j, p in enumerate(poly.split()):
            x, y = p.split(',')
            x = round(float(x) * 2)
            y = round(float(y) * 2)
            assert 0 <= x <= 10 and 0 <= y <= 22, (c, p)
            if j == 0 and k > 0:
                out.append(0xFF)
            out.append(x * 23 + y)
    out.append(0xFE)
print("/* Generated by tables.py. The stroke font: the arcade font's glyphs (crates/terse-mame-crt,")
print(" * src/arcade.rs: this project's own Apache-2.0 glyphs). A point is x * 23 + y")
print(" * on the doubled grid (x 0-10 across, y 0-22 down, 20 the baseline); FFh lifts")
print(" * the pen, FEh ends the glyph. */")
print("static const uint16_t font_index[%d] = {" % len(idx))
for i in range(0, len(idx), 16):
    print("    " + ", ".join(map(str, idx[i:i + 16])) + ",")
print("};")
print("static const uint8_t font_points[%d] = {" % len(out))
for i in range(0, len(out), 20):
    print("    " + ", ".join(map(str, out[i:i + 20])) + ",")
print("};")
amap = [want.index(chr(c)) if chr(c) in want else 255 for c in range(32, 96)]
print("/* The glyph of each character from ' ' to '_' (FFh: none, drawn as a space). */")
print("static const uint8_t font_ascii[64] = {")
for i in range(0, 64, 16):
    print("    " + ", ".join(map(str, amap[i:i + 16])) + ",")
print("};")
v = [round(127 * math.sin(2 * math.pi * i / 256)) for i in range(256)]
print("/* 127 sin(2 pi i / 256). */")
print("static const int8_t sintab[256] = {")
for i in range(0, 256, 16):
    print("    " + ", ".join("%4d" % x for x in v[i:i + 16]) + ",")
print("};")
