//! programs/fetch/fetch.terse with a simulated host that knows one blob,
//! message.txt, and completes every request at the start of the next frame
//! (as `terse run` does): the golden screen (programs/fetch/
//! expected-screen.txt; UPDATE_GOLDEN=1 rewrites it), not found, Esc exits,
//! and message_id.h and the image are up to date.

mod common;

use terse_core::{Completion, Event, FrameInput, Image, Machine, Outcome, Request, RequestKind};
use terse_net::blob_id;

const IMAGE: &[u8] = include_bytes!("../../../programs/fetch/fetch.terse");
const MESSAGE: &[u8] = include_bytes!("../../../programs/fetch/message.txt");

/// What a host with `blobs` in its store answers.
fn serve(requests: Vec<Request>, blobs: &[&[u8]]) -> Vec<Completion> {
    requests
        .into_iter()
        .map(|Request { handle, kind }| {
            let outcome = match kind {
                RequestKind::Get { id, offset, length } => match blobs.iter().find(|b| blob_id(b) == id) {
                    Some(blob) => {
                        let start = (offset as usize).min(blob.len());
                        let end = (start + length as usize).min(blob.len());
                        Outcome::Got { size: blob.len() as u32, data: blob[start..end].to_vec() }
                    }
                    None => Outcome::NotFound,
                },
                RequestKind::Put { data } => Outcome::Put { id: blob_id(&data) },
                RequestKind::Subscriptions { .. } | RequestKind::Timeline { .. } => {
                    Outcome::Records { total: 0, data: Vec::new() }
                }
            };
            Completion { handle, outcome }
        })
        .collect()
}

fn run(frames: u32, blobs: &[&[u8]], escape_at: Option<u32>) -> (Machine, Vec<u64>) {
    let mut m = Machine::new(&Image::parse(IMAGE).unwrap());
    let mut completions = Vec::new();
    let mut used = Vec::new();
    for f in 0..frames {
        let events: Vec<Event> = (escape_at == Some(f)).then(|| Event::key_down(0x29, 0)).into_iter().collect();
        let r = m.run_frame(&FrameInput { events: &events, completions: &completions, ..Default::default() });
        assert_eq!(r.completions_ignored, 0);
        assert!(m.fault().is_none(), "{:?}", m.fault());
        used.push(r.used);
        if r.stopped.is_some() {
            break;
        }
        completions = serve(m.take_content_requests(), blobs);
    }
    (m, used)
}

#[test]
fn fetch_screen() {
    let (m, used) = run(10, &[MESSAGE], None);
    let got = m.terminal().unwrap().text();
    common::golden("fetch/expected-screen.txt", &got);
    assert!(got.contains(std::str::from_utf8(MESSAGE).unwrap().lines().nth(3).unwrap()));
    let put_data: Vec<u8> = (0..=255).collect();
    let hex = terse_net::to_hex(&blob_id(&put_data));
    assert!(got.contains(&format!("blob ID: {}…", &hex[..16])), "{got}");
    let stats = common::FrameStats::new(&used);
    eprintln!("fetch: {}; deepest stack {} bytes", stats.describe(), stack_depth(&m));
}

fn stack_depth(m: &Machine) -> u32 {
    terse_core::RAM_BASE + m.ram().len() as u32 - m.cpu().min_sp
}

#[test]
fn fetch_not_found() {
    let (m, _) = run(10, &[], None);
    let text = m.terminal().unwrap().text();
    assert!(text.contains("fetching… status 02 not found"), "{text}");
    assert!(text.contains("Putting 256 bytes built in RAM… status 01 done"), "{text}");
    assert!(!text.contains("size:"), "{text}");
    assert!(text.contains("Esc: exit."), "{text}");
}

#[test]
fn fetch_exits_on_escape() {
    let (m, _) = run(20, &[MESSAGE], Some(6));
    assert_eq!(m.exit_code(), Some(0));
    assert_eq!(m.frame(), 7, "no frames run after the exit");
}

/// message_id.h is what build.sh writes for message.txt, and the image is
/// what build.sh makes.
#[test]
fn image_is_up_to_date() {
    let id = blob_id(MESSAGE);
    let bytes: Vec<String> = id.iter().map(|b| format!("0x{b:02x}")).collect();
    let header = format!(
        "/* Generated by build.sh: the blob ID (BLAKE3-256) of message.txt. */\n\
         static const uint8_t message_id[32] = {{\n    {},\n}};\n",
        bytes.join(", ")
    );
    let checked_in = std::fs::read_to_string(common::programs().join("fetch/message_id.h")).unwrap();
    assert!(header == checked_in, "programs/fetch/message_id.h is stale; run programs/fetch/build.sh");
    common::check_up_to_date(IMAGE, &["fetch/fetch.c"], true, "fetch", 1, &[(2, 0), (4, 0)]);
}
