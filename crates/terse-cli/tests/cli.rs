use std::path::{Path, PathBuf};
use std::process::Command;

const TERSE: &str = env!("CARGO_BIN_EXE_terse");

fn hello_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../programs/hello")
}

fn terse(args: &[&str]) -> std::process::Output {
    Command::new(TERSE).args(args).output().unwrap()
}

/// Runs `terse` and requires success.
fn terse_ok(args: &[&str]) -> std::process::Output {
    let out = terse(args);
    assert!(out.status.success(), "terse {args:?}: {}", String::from_utf8_lossy(&out.stderr));
    out
}

/// The checked-in hello.terse is what build.sh produces from hello.asm.
#[test]
fn hello_image_is_up_to_date() {
    let tmp = Path::new(env!("CARGO_TARGET_TMPDIR"));
    let bin = tmp.join("hello.bin");
    let image = tmp.join("hello.terse");
    let asm = hello_dir().join("hello.asm");
    terse_ok(&["asm", asm.to_str().unwrap(), "-o", bin.to_str().unwrap()]);
    terse_ok(&[
        "pack", "--rom", bin.to_str().unwrap(), "--title", "hello", "--ram-pages", "4",
        "--device", "2:0", "-o", image.to_str().unwrap(),
    ]);
    let built = std::fs::read(&image).unwrap();
    let checked_in = std::fs::read(hello_dir().join("hello.terse")).unwrap();
    assert!(built == checked_in, "programs/hello/hello.terse is stale; run programs/hello/build.sh");
}

fn fetch_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../programs/fetch")
}

/// The checked-in message_id.inc and fetch.terse are what build.sh produces.
#[test]
fn fetch_image_is_up_to_date() {
    let message = fetch_dir().join("message.txt");
    let out = terse_ok(&["hash", message.to_str().unwrap()]);
    let id = String::from_utf8(out.stdout).unwrap().trim().to_string();
    assert_eq!(id, terse_net::to_hex(&terse_net::blob_id(&std::fs::read(&message).unwrap())));
    let bytes: Vec<String> = (0..32).map(|i| format!("0x{}", &id[2 * i..2 * i + 2])).collect();
    let inc = format!(
        "; Generated by build.sh: the blob ID (BLAKE3-256) of message.txt.\nmessage_id:\n        db {}\n",
        bytes.join(",")
    );
    let checked_in = std::fs::read_to_string(fetch_dir().join("message_id.inc")).unwrap();
    assert!(inc == checked_in, "programs/fetch/message_id.inc is stale; run programs/fetch/build.sh");

    let tmp = Path::new(env!("CARGO_TARGET_TMPDIR"));
    let bin = tmp.join("fetch.bin");
    let image = tmp.join("fetch.terse");
    let asm = fetch_dir().join("fetch.asm");
    terse_ok(&["asm", asm.to_str().unwrap(), "-o", bin.to_str().unwrap()]);
    terse_ok(&[
        "pack", "--rom", bin.to_str().unwrap(), "--title", "fetch", "--ram-pages", "4",
        "--device", "2:0", "--device", "4:0", "-o", image.to_str().unwrap(),
    ]);
    let built = std::fs::read(&image).unwrap();
    let checked_in = std::fs::read(fetch_dir().join("fetch.terse")).unwrap();
    assert!(built == checked_in, "programs/fetch/fetch.terse is stale; run programs/fetch/build.sh");
}

#[test]
fn put_get_and_run_by_id_without_a_relay() {
    let store = tempfile::tempdir().unwrap();
    let store = store.path().to_str().unwrap();
    let image = hello_dir().join("hello.terse");
    let out = terse_ok(&["put", image.to_str().unwrap(), "--store", store]);
    let id = String::from_utf8(out.stdout).unwrap().trim().to_string();
    let out = terse_ok(&["info", &id, "--store", store]);
    assert!(String::from_utf8(out.stdout).unwrap().contains(&format!("id:        {id}")));
    let out = terse(&["run", &id, "--store", store, "--frames", "3", "--dump"]);
    assert!(String::from_utf8(out.stdout).unwrap().contains("héllo, wörld — 你好"));
    let out = terse_ok(&["get", &id, "--store", store]);
    assert!(out.stdout == std::fs::read(&image).unwrap());

    let missing = "00".repeat(32);
    let out = terse(&["get", &missing, "--store", store]);
    assert!(!out.status.success());
    assert!(String::from_utf8_lossy(&out.stderr).contains("not found"));
    let out = terse(&["put", "/dev/null", "--store", store]);
    assert!(!out.status.success());
}

#[test]
fn info_and_run() {
    let image = hello_dir().join("hello.terse");
    let out = terse_ok(&["info", image.to_str().unwrap()]);
    let text = String::from_utf8(out.stdout).unwrap();
    assert!(text.contains("title:     hello"), "{text}");
    assert!(text.contains("devices:   2:0"), "{text}");

    let out = terse(&["run", image.to_str().unwrap(), "--frames", "3", "--dump"]);
    assert_eq!(out.status.code(), Some(0));
    let text = String::from_utf8(out.stdout).unwrap();
    assert_eq!(text.lines().count(), 30);
    assert!(text.contains("héllo, wörld — 你好"));
    assert!(text.contains("frame 00000002"));
}

#[test]
fn run_exit_code_is_the_machines() {
    let tmp = Path::new(env!("CARGO_TARGET_TMPDIR"));
    let rom = tmp.join("exit7.bin");
    let image = tmp.join("exit7.terse");
    std::fs::write(&rom, [0x3E, 7, 0xD3, 0x1F, 0x18, 0xFE]).unwrap(); // ld a,7; out (1Fh),a; jr $
    let (rom, image) = (rom.to_str().unwrap(), image.to_str().unwrap());
    terse_ok(&["pack", "--rom", rom, "--title", "x", "--ram-pages", "4", "-o", image]);
    let out = terse(&["run", image]);
    assert_eq!(out.status.code(), Some(7));
}

