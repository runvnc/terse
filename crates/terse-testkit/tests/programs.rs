//! The mechanism that keeps tests from running programs older than their
//! sources: a program whose sources changed after it was built is rebuilt
//! before a test gets it, and one that cannot be built fails the test.

use std::path::Path;
use std::process::Command;
use std::time::{Duration, SystemTime};

fn cargo() -> Command {
    Command::new(std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into()))
}

fn write(path: &Path, text: &str) {
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, text).unwrap();
}

fn output(exe: &Path) -> String {
    String::from_utf8(Command::new(exe).output().unwrap().stdout).unwrap()
}

/// A workspace of its own, with its own target directory, holding one
/// program that prints `text`.
fn project(dir: &Path, text: &str) {
    write(&dir.join("Cargo.toml"), "[workspace]\nmembers = [\"probe\"]\nresolver = \"3\"\n");
    write(
        &dir.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"probe\"\nversion = \"0.1.0\"\n",
    );
    write(
        &dir.join("probe/Cargo.toml"),
        "[package]\nname = \"probe\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[[bin]]\nname = \"stale-probe\"\npath = \"main.rs\"\n",
    );
    set_text(dir, text, SystemTime::now() - Duration::from_secs(60));
}

/// The program's source, changed at `time`.
fn set_text(dir: &Path, text: &str, time: SystemTime) {
    let src = dir.join("probe/main.rs");
    write(&src, &format!("fn main() {{ print!(\"{text}\"); }}\n"));
    std::fs::File::options().write(true).open(&src).unwrap().set_modified(time).unwrap();
}

fn build(dir: &Path) -> terse_testkit::Built {
    let mut cargo = cargo();
    cargo.env("CARGO_TARGET_DIR", dir.join("target"));
    terse_testkit::build(cargo, &dir.join("Cargo.toml"), None, &["stale-probe"]).unwrap()
}

#[test]
fn a_program_older_than_its_sources_is_rebuilt() {
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();
    project(dir, "one");
    let first = build(dir);
    assert_eq!(first.rebuilt, ["stale-probe"]);
    let exe = &first.programs[0].1;
    assert_eq!(output(exe), "one");

    // Up to date: nothing is built.
    let again = build(dir);
    assert!(again.rebuilt.is_empty(), "{again:?}");
    assert_eq!(&again.programs[0].1, exe);

    // The sources change after the build: the binary there is out of date
    // (what a test found by path would have run), and asking for it
    // rebuilds it.
    // (Later than the build, whatever the file system's clock granularity.)
    set_text(dir, "two", SystemTime::now() + Duration::from_secs(2));
    assert_eq!(output(exe), "one", "the planted binary is the old one");
    let after = build(dir);
    assert_eq!(after.rebuilt, ["stale-probe"]);
    assert_eq!(output(&after.programs[0].1), "two");
}

#[test]
fn a_program_that_cannot_be_built_is_an_error() {
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();
    project(dir, "one");
    let mut cargo = cargo();
    cargo.env("CARGO_TARGET_DIR", dir.join("target"));
    let e = terse_testkit::build(cargo, &dir.join("Cargo.toml"), None, &["no-such-program"]).unwrap_err();
    assert!(e.contains("no-such-program"), "{e}");

    // A compile error.
    write(&dir.join("probe/main.rs"), "fn main() { not rust }\n");
    let mut cargo = self::cargo();
    cargo.env("CARGO_TARGET_DIR", dir.join("target"));
    let e = terse_testkit::build(cargo, &dir.join("Cargo.toml"), None, &["stale-probe"]).unwrap_err();
    assert!(e.contains("building stale-probe for this test failed"), "{e}");
}

/// In this workspace, from inside `cargo test`: the build is not blocked by
/// the `cargo test` that runs this (cargo does not hold its lock on the
/// target directory while tests run), and gives a program that runs.
#[test]
fn a_workspace_program() {
    // terse-bus: no package's tests make cargo build it.
    let bus = terse_testkit::program("terse-bus");
    let out = Command::new(&bus).arg("--version").output().unwrap();
    assert!(out.status.success(), "{bus:?}: {out:?}");
    assert!(String::from_utf8_lossy(&out.stdout).starts_with("terse-bus "), "{out:?}");
    assert_eq!(terse_testkit::program_dir("terse-bus"), bus.parent().unwrap());
}
