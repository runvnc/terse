//! Differential tests: tests/torture/torture.c (shifts, multiplication and
//! division of every width, comparisons, loads and stores of every width
//! and alignment, recursion, function pointers, a CRC, a sort, an
//! interpreter of PRNG-generated programs, and a set of random expressions
//! generated here) is compiled natively for this host and for rv32imc at
//! -O0, -Os and -O2. The checksums the guest prints on the terminal must be
//! those the native build prints. Skipped without the RISC-V tools.

mod common;

use std::fmt::Write as _;
use std::path::Path;
use std::process::Command;

use terse_core::Machine;

struct Gen(u64);

impl Gen {
    fn next(&mut self) -> u32 {
        self.0 = self.0.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
        (self.0 >> 33) as u32
    }

    fn below(&mut self, n: u32) -> u32 {
        self.next() % n
    }

    /// A random expression of type uint32_t over a, b, c; no undefined
    /// behaviour with -fwrapv.
    fn expr(&mut self, depth: u32) -> String {
        if depth == 0 || self.below(5) == 0 {
            return match self.below(6) {
                0 => "a".into(),
                1 => "b".into(),
                2 => "c".into(),
                3 => format!("{}u", self.next()),
                4 => format!("{}u", self.below(64)),
                _ => format!("0x{:x}u", 1u32 << self.below(32)),
            };
        }
        let d = depth - 1;
        match self.below(30) {
            0 => format!("(~{})", self.expr(d)),
            1 => format!("(0u - {})", self.expr(d)),
            2 => format!("((uint32_t)(int8_t){})", self.expr(d)),
            3 => format!("((uint32_t)(int16_t){})", self.expr(d)),
            4 => format!("((uint32_t)(uint16_t){})", self.expr(d)),
            5 => format!("((uint32_t)!{})", self.expr(d)),
            6 => format!("({} + {})", self.expr(d), self.expr(d)),
            7 => format!("({} - {})", self.expr(d), self.expr(d)),
            8 => format!("({} * {})", self.expr(d), self.expr(d)),
            9 => format!("({} & {})", self.expr(d), self.expr(d)),
            10 => format!("({} | {})", self.expr(d), self.expr(d)),
            11 => format!("({} ^ {})", self.expr(d), self.expr(d)),
            12 => format!("({} << ({} & 31))", self.expr(d), self.expr(d)),
            13 => format!("({} >> ({} & 31))", self.expr(d), self.expr(d)),
            14 => format!("((uint32_t)((int32_t){} >> ({} & 31)))", self.expr(d), self.expr(d)),
            15 => format!("({} / ({} | 1u))", self.expr(d), self.expr(d)),
            16 => format!("({} % ({} | 1u))", self.expr(d), self.expr(d)),
            17 => format!("sdiv_({}, {})", self.expr(d), self.expr(d)),
            18 => format!("srem_({}, {})", self.expr(d), self.expr(d)),
            19 => format!("((uint32_t)({} < {}))", self.expr(d), self.expr(d)),
            20 => format!("((uint32_t)((int32_t){} < (int32_t){}))", self.expr(d), self.expr(d)),
            21 => format!("((uint32_t)({} == {}))", self.expr(d), self.expr(d)),
            22 => format!("mulhu_({}, {})", self.expr(d), self.expr(d)),
            23 => format!("mulh_({}, {})", self.expr(d), self.expr(d)),
            24 => format!("mulhsu_({}, {})", self.expr(d), self.expr(d)),
            25 => format!("({} ? {} : {})", self.expr(d), self.expr(d), self.expr(d)),
            26 => format!("((int32_t){} < 0 ? {} : {})", self.expr(d), self.expr(d), self.expr(d)),
            27 => format!("((uint32_t)(int16_t)({} * {}))", self.expr(d), self.expr(d)),
            28 => format!("((uint32_t)(uint8_t){} / ((uint32_t)(uint8_t){} | 1u))", self.expr(d), self.expr(d)),
            _ => format!("(({} >> 3) + ({} << 5))", self.expr(d), self.expr(d)),
        }
    }
}

fn generated_header(count: usize) -> String {
    let mut g = Gen(0x5DEE_CE66_D1CE_4E5B);
    let mut out = String::from(
        "/* Generated by crates/terse-rv/tests/differential.rs. */\n\
         static inline uint32_t sdiv_(uint32_t x, uint32_t y) {\n\
         \x20   int32_t a = (int32_t)x, b = (int32_t)(y | 1u);\n\
         \x20   return b == -1 ? (uint32_t)0 - x : (uint32_t)(a / b);\n}\n\
         static inline uint32_t srem_(uint32_t x, uint32_t y) {\n\
         \x20   int32_t a = (int32_t)x, b = (int32_t)(y | 1u);\n\
         \x20   return b == -1 ? 0u : (uint32_t)(a % b);\n}\n\
         static inline uint32_t mulhu_(uint32_t x, uint32_t y) { return (uint32_t)(((uint64_t)x * y) >> 32); }\n\
         static inline uint32_t mulh_(uint32_t x, uint32_t y) { return (uint32_t)((uint64_t)((int64_t)(int32_t)x * (int32_t)y) >> 32); }\n\
         static inline uint32_t mulhsu_(uint32_t x, uint32_t y) { return (uint32_t)((uint64_t)((int64_t)(int32_t)x * (int64_t)(uint64_t)y) >> 32); }\n",
    );
    for k in 0..count {
        let _ = writeln!(out, "static uint32_t gen_{k}(uint32_t a, uint32_t b, uint32_t c) {{ return {}; }}", g.expr(5));
    }
    let _ = writeln!(out, "#define GEN_COUNT {count}");
    out += "static uint32_t (*const gen[])(uint32_t, uint32_t, uint32_t) = {\n";
    for k in 0..count {
        let _ = writeln!(out, "    gen_{k},");
    }
    out += "};\n";
    out
}

fn sources(dir: &Path) -> std::path::PathBuf {
    let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/torture/torture.c");
    std::fs::copy(&src, dir.join("torture.c")).unwrap();
    std::fs::write(dir.join("generated.h"), generated_header(120)).unwrap();
    dir.join("torture.c")
}

fn native(dir: &Path) -> String {
    let exe = dir.join("torture-native");
    let out = Command::new("clang")
        .args(["-O2", "-fwrapv", "-DTERSE_NATIVE", "-o"])
        .arg(&exe)
        .arg(dir.join("torture.c"))
        .output()
        .unwrap();
    assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stderr));
    let out = Command::new(&exe).output().unwrap();
    assert!(out.status.success());
    String::from_utf8(out.stdout).unwrap()
}

#[test]
fn torture_matches_native() {
    if !common::have_tools() {
        return;
    }
    let dir = tempfile::tempdir().unwrap();
    let src = sources(dir.path());
    let want = native(dir.path());
    assert!(want.lines().count() == 12 && want.ends_with("end\n"), "{want}");
    for opt in ["-O0", "-Os", "-O2"] {
        let rom = common::build(std::slice::from_ref(&src), opt, true);
        let mut m = Machine::new(&common::program(&rom, 4, &[common::TERMINAL]));
        let mut frames = 0;
        while m.exit_code().is_none() && frames < 2000 {
            m.run_frame(&Default::default());
            frames += 1;
        }
        assert_eq!(m.fault(), None, "{opt}");
        assert_eq!(m.exit_code(), Some(0), "{opt}: no exit after {frames} frames");
        let got: String = m.terminal().unwrap().text().lines().filter(|l| !l.is_empty()).map(|l| format!("{l}\n")).collect();
        assert_eq!(got, want, "{opt}");
        eprintln!(
            "torture {opt}: ROM {} bytes, {} instructions, {} calls, {frames} frames",
            rom.len(),
            m.instructions(),
            m.calls()
        );
    }
}
